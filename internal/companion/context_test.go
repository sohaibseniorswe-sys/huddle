func TestContextString(t *testing.T) {
	c := Context{
		Screen:    `Log view, Codex turn 5, opened at 22:52:07 from the Activity line "$ gh pr create → PR #73"`,
		State:     "state:dev-working, Dev (Codex) running for 12m, turn 5",
		Milestone: "Milestone 3, 4 of 7 issues closed (#59 #60 #61 #63 closed; #62 #64 #65 open)",
		Events:    []string{"22:52 codex $ gh pr create → PR #73", "22:52 codex Waiting for CI on PR #73"},
		Comments:  []string{"pm at 23:03:\nUse JSON for the export."},
		PMOutput:  "Handed #62 to Codex.",
	}
	want := `HUDDLE CONTEXT (generated by Huddle; not typed by the human)
Screen: Log view, Codex turn 5, opened at 22:52:07 from the Activity line "$ gh pr create → PR #73"
State: state:dev-working, Dev (Codex) running for 12m, turn 5
Milestone: Milestone 3, 4 of 7 issues closed (#59 #60 #61 #63 closed; #62 #64 #65 open)
Last 2 activity events:
  22:52 codex $ gh pr create → PR #73
  22:52 codex Waiting for CI on PR #73
Latest control issue comments (newest 1, trimmed):
  pm at 23:03:
  Use JSON for the export.
PM's last output (trimmed):
  Handed #62 to Codex.
Running agent's latest output (last 40 lines): none
Pending decision card: none`
	if got := c.String(); got != want {
		t.Errorf("String() =\n%s\n\nwant\n%s", got, want)
	}
}

func TestContextStaysShort(t *testing.T) {
	var c Context
	for i := range 40 {
		c.Events = append(c.Events, fmt.Sprintf("event %d", i))
		c.Comments = append(c.Comments, fmt.Sprintf("comment %d %s", i, strings.Repeat("x", 2000)))
	}
	var out []string
	for i := range 100 {
		out = append(out, fmt.Sprintf("output line %d", i))
	}
	c.AgentOutput = strings.Join(out, "\n")
	got := c.String()

	if strings.Contains(got, "event 24\n") || !strings.Contains(got, "event 25\n") || !strings.Contains(got, "event 39") {
		t.Error("want exactly the newest 15 events")
	}
	if strings.Contains(got, "comment 36 ") || !strings.Contains(got, "comment 37 ") {
		t.Error("want exactly the newest 3 comments")
	}
	if !strings.Contains(got, "…(trimmed)") {
		t.Error("a long comment must be trimmed")
	}
	if strings.Contains(got, "output line 59\n") || !strings.Contains(got, "output line 60\n") {
		t.Error("want exactly the last 40 output lines")
	}
	if len(got) > 6000 {
		t.Errorf("context block is %d bytes", len(got))
	}
}
