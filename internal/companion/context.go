package companion

import (
	"fmt"
	"strings"
)

// The sizes that keep the context block short.
const (
	// MaxEvents is how many of the newest Activity events go in.
	MaxEvents = 15
	// MaxComments is how many of the newest control issue comments go in.
	MaxComments = 3
	// AgentOutputLines is how many of the running agent's last output
	// lines go in.
	AgentOutputLines = 40
	// maxCommentChars and maxPMChars trim a long comment and the PM's
	// last output.
	maxCommentChars = 800
	maxPMChars      = 1500
)

// contextHeader opens every context block. It tells the companion that
// Huddle, not the human, wrote what follows.
const contextHeader = "HUDDLE CONTEXT (generated by Huddle; not typed by the human)"

// Context is what Huddle tells the companion with every message: what the
// human sees and what is happening. The run screen fills it in fresh for
// each message; String turns it into the plain-text block.
type Context struct {
	// Screen describes the human's screen: "Log view, Codex turn 5,
	// opened at 22:52:07 from the Activity line ...".
	Screen string
	// State is the loop's state: "state:dev-working, Dev (Codex) running
	// for 12m, turn 5".
	State string
	// Milestone is its progress: "Milestone 3, 4 of 7 issues closed (...)".
	Milestone string
	// Events are the newest Activity events, oldest first, one line each:
	// "22:52 codex $ gh pr create → PR #73".
	Events []string
	// Comments are the newest control issue comments, oldest first, each
	// starting with its author and time.
	Comments []string
	// PMOutput is the PM's final message from its last turn; "" if none.
	PMOutput string
	// AgentOutput is the running agent's last output lines; "" if no agent
	// is running.
	AgentOutput string
	// PendingCard describes the card waiting for the human; "" if none.
	PendingCard string
}

// String returns the context block. Long parts are trimmed, so the block
// stays short however long the run.
func (c Context) String() string {
	var b strings.Builder
	line := func(name, value string) { fmt.Fprintf(&b, "%s: %s\n", name, value) }

	b.WriteString(contextHeader + "\n")
	line("Screen", orNone(c.Screen))
	line("State", orNone(c.State))
	line("Milestone", orNone(c.Milestone))

	events := c.Events[max(len(c.Events)-MaxEvents, 0):]
	fmt.Fprintf(&b, "Last %d activity events:", len(events))
	if len(events) == 0 {
		b.WriteString(" none")
	}
	b.WriteString("\n")
	for _, e := range events {
		b.WriteString("  " + oneLine(e) + "\n")
	}

	comments := c.Comments[max(len(c.Comments)-MaxComments, 0):]
	fmt.Fprintf(&b, "Latest control issue comments (newest %d, trimmed):", len(comments))
	if len(comments) == 0 {
		b.WriteString(" none")
	}
	b.WriteString("\n")
	for _, com := range comments {
		b.WriteString(indent(trim(com, maxCommentChars)) + "\n")
	}

	b.WriteString("PM's last output (trimmed):")
	writeBlock(&b, trim(c.PMOutput, maxPMChars))
	fmt.Fprintf(&b, "Running agent's latest output (last %d lines):", AgentOutputLines)
	writeBlock(&b, tailLines(c.AgentOutput, AgentOutputLines))
	line("Pending decision card", orNone(c.PendingCard))
	return strings.TrimRight(b.String(), "\n")
}

// writeBlock writes text indented on the lines after a heading, or " none".
func writeBlock(b *strings.Builder, text string) {
	if strings.TrimSpace(text) == "" {
		b.WriteString(" none\n")
		return
	}
	b.WriteString("\n" + indent(text) + "\n")
}

// orNone returns s, or "none" if it is empty.
func orNone(s string) string {
	if strings.TrimSpace(s) == "" {
		return "none"
	}
	return s
}

// oneLine joins the lines of s with spaces.
func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

// indent indents every line of s by two spaces.
func indent(s string) string {
	lines := strings.Split(strings.TrimRight(s, "\n"), "\n")
	for i, l := range lines {
		lines[i] = "  " + l
	}
	return strings.Join(lines, "\n")
}

// trim cuts s to at most n bytes, at a rune boundary, marking the cut.
func trim(s string, n int) string {
	s = strings.TrimSpace(s)
	if len(s) <= n {
		return s
	}
	cut := n
	for cut > 0 && !isRuneStart(s[cut]) {
		cut--
	}
	return s[:cut] + " …(trimmed)"
}

// isRuneStart reports whether byte c starts a UTF-8 character.
func isRuneStart(c byte) bool { return c&0xC0 != 0x80 }

// tailLines returns the last n lines of s.
func tailLines(s string, n int) string {
	lines := strings.Split(strings.TrimRight(s, "\n"), "\n")
	return strings.Join(lines[max(len(lines)-n, 0):], "\n")
}
