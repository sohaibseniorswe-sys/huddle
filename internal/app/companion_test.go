func TestAgreePostsOneDecisionAndHandsToThePM(t *testing.T) {
	f := newDecisionFixture(t)
	before := len(f.gh.IssueComments[58])
	// The second Enter goes to the text field (and sends the half-typed
	// question): it must not post the decision twice.
	f.keys("tab", "/decision", "enter", "enter", "enter")

	comments := f.gh.IssueComments[58][before:]
	want := "<!-- huddle:decision -->\n**Decision** (agreed in Huddle)\n\n" +
		"Use MapLibre with OpenStreetMap tiles for #65 now (no API key). Add a follow-up issue in Milestone 4 to switch to Mapbox once the token exists.\n\n" +
		"Reason: no Mapbox token yet; MapLibre keeps #65's acceptance criteria.\n"
	if len(comments) != 1 || comments[0].Body != want {
		t.Fatalf("posted %d comments: %+v\nwant one:\n%s", len(comments), comments, want)
	}
	if got := f.gh.Issues[0].Labels; !slices.Equal(got, []string{"control", gh.StatePMReady}) {
		t.Errorf("labels = %v, want state:pm-ready", got)
	}
	if f.m.card.kind != cardNone || f.m.focus != focusInput {
		t.Errorf("card %v, focus %d after Agree", f.m.card.kind, f.m.focus)
	}
	found := false
	for _, e := range f.m.events {
		if e.Actor == activity.ActorYou && e.Text == "Decision posted on #58" {
			found = true
		}
	}
	if !found {
		t.Errorf("no you event \"Decision posted on #58\" in %q", f.eventTexts())
	}
	if !slices.ContainsFunc(f.m.chat, func(e companion.Entry) bool { return e.Who == companion.WhoDecision }) {
		t.Error("the conversation does not record the decision")
	}
	if !strings.Contains(f.m.statusContent(), "1 agreed · last 00:02 Use MapLibre") {
		t.Errorf("/status does not count the decision:\n%s", f.m.statusContent())
	}
}

