func TestPlainTextGoesToTheCompanion(t *testing.T) {
	f := newFixture(t)
	f.comp.replies = []string{"Codex is on #62."}
	f.keys("What is Codex doing?", "enter")

	if !f.m.companionOpen {
		t.Error("sending a message must open the Companion pane")
	}
	got := f.comp.lastAsked()
	if got.message != "What is Codex doing?" {
		t.Errorf("companion was asked %q", got.message)
	}
	if !strings.HasPrefix(got.context, "HUDDLE CONTEXT (generated by Huddle; not typed by the human)\n") {
		t.Errorf("the message must come with the context block:\n%s", got.context)
	}
	if last := f.m.chat[len(f.m.chat)-1]; last.Who != companion.WhoCompanion || last.Text != "Codex is on #62." {
		t.Errorf("last chat entry = %+v", last)
	}
	if f.m.thinking || f.m.input.Value() != "" {
		t.Errorf("thinking = %t, text field %q", f.m.thinking, f.m.input.Value())
	}
	if len(f.gh.IssueComments) != 0 {
		t.Errorf("plain text was posted on GitHub: %v", f.gh.IssueComments)
	}
}

